#!/usr/bin/env python3
"""Render the reviewed capability and source-inventory documentation."""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from custom_components.nice_bidiwifi.feature_catalog import (  # noqa: E402
    FEATURES,
    FEATURES_BY_KEY,
    GAPS,
    GAPS_BY_KEY,
    app_inventory,
)


def documents() -> dict[str, str]:
    inventory = app_inventory()
    entries = inventory["entries"]
    for row in entries:
        if row["destination"] not in FEATURES_BY_KEY or any(
            key not in GAPS_BY_KEY for key in row["gaps"]
        ):
            raise ValueError(f"Unmapped source evidence: {row['id']}")
    counts = Counter(row["kind"] for row in entries)
    lines = [
        "# App parity inventory",
        "",
        "Generated by `scripts/render_capabilities.py`. Edit the catalog or source index, then regenerate.",
        "",
        "Target: the combined capabilities of MyNice Welcome 1.3.1 and MyNice Pro 2.18 r188. This is an evidence and delivery inventory, not a claim of completed parity or universal hardware support.",
        "",
        f"The supplied JADX exports contain {len(entries)} indexed primary source items. Alternate decompiler passes are deduplicated by relative Java path, preferring fewer unrecovered methods. Synthetic classes, generated bindings/navigation helpers and build resources are excluded. Supporting classes retain their methods so event paths and repository helpers are not silently omitted.",
        "",
        "The complete machine-readable index is [app_inventory.json](../custom_components/nice_bidiwifi/app_inventory.json). Every entry has a stable ID, app version, relative source path, SHA-256, public/native/unrecovered methods, delivery destination, phase and known gap dependencies. Destination assignment is an initial routing by source name; phase implementation must follow the actual call path and refine it. One source item can serve several user features. App IDs and enum constructors are not wire codes.",
        "",
        "## Source coverage",
        "",
        "| Kind | Items |",
        "| --- | ---: |",
    ]
    lines += [f"| {kind} | {count} |" for kind, count in sorted(counts.items())]
    lines += [
        "",
        "## Delivery destinations",
        "",
        "| Destination | Phase | Indexed items |",
        "| --- | ---: | ---: |",
    ]
    destinations = Counter(row["destination"] for row in entries)
    lines += [
        f"| `{key}` | {FEATURES_BY_KEY[key].phase} | {count} |"
        for key, count in sorted(destinations.items())
    ]
    lines += [
        "",
        "## Reviewed runtime features",
        "",
        "Implementation, device support, permissions and current availability are separate axes. An implemented operation may still be unsupported, denied, offline or unsafe while moving. Unknown permissions stay unknown. Existing compatibility controls retain their existing fallback and on-demand reconnect rules.",
        "",
        "| Feature | Implementation | Phase | Binding | Gaps |",
        "| --- | --- | ---: | --- | --- |",
    ]
    lines += [
        f"| `{feature.key}` | {feature.implementation} | {feature.phase} | {feature.binding.handler if feature.binding else 'none'} | {', '.join(feature.gaps) or 'none'} |"
        for feature in FEATURES
    ]
    lines += [
        "",
        "## Controller command evidence",
        "",
        "These entries include invalid/sentinel and transport-specific enum values. They establish what the exported app names, not what HA may execute.",
        "",
        "| App symbol | App ID | Destination | Phase |",
        "| --- | ---: | --- | ---: |",
    ]
    lines += [
        f"| `{row['symbol']}` | {row['app_command_id'] if row['app_command_id'] is not None else 'unresolved'} | `{row['destination']}` | {row['phase']} |"
        for row in entries
        if row["kind"] == "controller_command"
    ]
    gaps = [
        "# Protocol and evidence gaps",
        "",
        "Generated by `scripts/render_capabilities.py`. Unknown values remain null and cannot reach a device.",
        "",
    ]
    for gap in GAPS:
        references = [row["id"] for row in entries if gap.key in row["gaps"]]
        gaps += [
            f"## `{gap.key}`",
            "",
            gap.summary + ".",
            "",
            f"Missing: {gap.missing}",
            "",
            f"To unblock: {gap.completion}",
            "",
            f"Indexed source dependencies: {len(references)}. Full references are in the source inventory.",
            "",
        ]
    gaps += [
        "Filling a numeric placeholder alone does not establish model support, permissions, payload encoding or procedure recovery. A completed binding needs reviewed targeting, value validation, request/reply fixtures, failure tests and a complete procedure state machine when applicable.",
        "",
    ]
    return {
        "docs/app_parity.md": "\n".join(lines) + "\n",
        "docs/protocol_gaps.md": "\n".join(gaps),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in documents().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Outdated generated documentation: {name}")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
