#!/usr/bin/env python3
"""Render the reviewed capability and source-inventory documentation."""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from custom_components.nice_bidiwifi.controller_catalog import PARAMETERS  # noqa: E402
from custom_components.nice_bidiwifi.feature_catalog import (  # noqa: E402
    FEATURES,
    FEATURES_BY_KEY,
    GAPS,
    GAPS_BY_KEY,
    app_inventory,
)
from custom_components.nice_bidiwifi.protocol.t4.settings import (  # noqa: E402
    ADDITIONAL_SETTINGS,
)


def documents() -> dict[str, str]:
    inventory = app_inventory()
    entries = inventory["entries"]
    for row in entries:
        if row["destination"] not in FEATURES_BY_KEY or any(
            key not in GAPS_BY_KEY for key in row["gaps"]
        ):
            raise ValueError(f"Unmapped source evidence: {row['id']}")
    counts = Counter(row["kind"] for row in entries)
    lines = [
        "# App parity inventory",
        "",
        "Generated by `scripts/render_capabilities.py`. Edit the catalog or source index, then regenerate.",
        "",
        "Target: the combined capabilities of MyNice Welcome 1.3.1 and MyNice Pro 2.18 r188. This is an evidence and delivery inventory, not a claim of completed parity or universal hardware support.",
        "",
        f"The supplied JADX exports contain {len(entries)} indexed primary source items. Alternate decompiler passes are deduplicated by relative Java path, preferring fewer unrecovered methods. Synthetic classes, generated bindings/navigation helpers and build resources are excluded. Supporting classes retain their methods so event paths and repository helpers are not silently omitted.",
        "",
        "The complete machine-readable index is [app_inventory.json](../custom_components/nice_bidiwifi/app_inventory.json). Every entry has a stable ID, app version, relative source path, SHA-256, public/native/unrecovered methods, delivery destination, phase and known gap dependencies. Destination assignment is an initial routing by source name; phase implementation must follow the actual call path and refine it. One source item can serve several user features. App IDs and enum constructors are not wire codes.",
        "",
        "## Source coverage",
        "",
        "| Kind | Items |",
        "| --- | ---: |",
    ]
    lines += [f"| {kind} | {count} |" for kind, count in sorted(counts.items())]
    lines += [
        "",
        "## Delivery destinations",
        "",
        "| Destination | Phase | Indexed items |",
        "| --- | ---: | ---: |",
    ]
    destinations = Counter(row["destination"] for row in entries)
    lines += [
        f"| `{key}` | {FEATURES_BY_KEY[key].phase} | {count} |"
        for key, count in sorted(destinations.items())
    ]
    lines += [
        "",
        "## Reviewed runtime features",
        "",
        "Implementation, device support, permissions and current availability are separate axes. An implemented operation may still be unsupported, denied, offline or unsafe while moving. Unknown permissions stay unknown. Existing compatibility controls retain their existing fallback and on-demand reconnect rules.",
        "",
        "| Feature | Implementation | Phase | Binding | Gaps |",
        "| --- | --- | ---: | --- | --- |",
    ]
    lines += [
        f"| `{feature.key}` | {feature.implementation} | {feature.phase} | {feature.binding.handler if feature.binding else 'none'} | {', '.join(feature.gaps) or 'none'} |"
        for feature in FEATURES
    ]
    lines += [
        "",
        "## Controller command evidence",
        "",
        "These entries include invalid/sentinel and transport-specific enum values. They establish what the exported app names, not what HA may execute.",
        "",
        "| App symbol | App ID | Destination | Phase |",
        "| --- | ---: | --- | ---: |",
    ]
    lines += [
        f"| `{row['symbol']}` | {row['app_command_id'] if row['app_command_id'] is not None else 'unresolved'} | `{row['destination']}` | {row['phase']} |"
        for row in entries
        if row["kind"] == "controller_command"
    ]
    gaps = [
        "# Protocol and evidence gaps",
        "",
        "Generated by `scripts/render_capabilities.py`. Unknown values remain null and cannot reach a device.",
        "",
    ]
    for gap in GAPS:
        references = [row["id"] for row in entries if gap.key in row["gaps"]]
        gaps += [
            f"## `{gap.key}`",
            "",
            gap.summary + ".",
            "",
            f"Missing: {gap.missing}",
            "",
            f"To unblock: {gap.completion}",
            "",
            f"Indexed source dependencies: {len(references)}. Full references are in the source inventory.",
            "",
        ]
    gaps += [
        "Filling a numeric placeholder alone does not establish model support, permissions, payload encoding or procedure recovery. A completed binding needs reviewed targeting, value validation, request/reply fixtures, failure tests and a complete procedure state machine when applicable.",
        "",
    ]
    configuration = [
        "# Controller configuration and app coverage",
        "",
        "Generated by `scripts/render_capabilities.py`. The source inventory is cross-checked, not an instruction to probe every register.",
        "",
        f"There are {len(PARAMETERS)} definitions: all 357 app command symbols plus the unmatched `04/BE` table row. The supplied 237-row controller table yields 236 group-04 bindings whose symbol and app ID both match the exported Java. Standard-group bindings extend the inventory beyond group 04. Other controller/radio/PSU bindings remain explicit gaps where the extraction cannot be cross-checked.",
        "",
        "## What is available",
        "",
        "The 25 verified Welcome/T4 actions retain their existing advertisement checks, compatibility defaults and entity IDs. This includes partial opening, master/slave, courtesy light and block/release commands. Extra Pro-only actions remain blocked where their code or lifecycle is unresolved; enum order and app IDs are never used as wire commands.",
        "",
        "Existing switches and numbers keep their IDs and raw integer service API. Two optional select entities add named photo-close and always-close choices alongside the old numbers. Optional engineering-unit number aliases use the controller's exact scale, range and step. Fractional raw values are rejected instead of rounded silently.",
        "",
        "The captured boolean INFO `01 00 01 41 02 00 01` is recognized as scalar off/on options. Structured diagnostic lists are still blocked by the scalar setter.",
        "",
        "Additional configuration sensors are disabled by default. Enabling one requests its reviewed INFO and scalar GET, without a broad speculative scan. Reads wait while moving/calibrating, run below status and user controls, and refresh in small batches. Metadata distinguishes missing, unsupported, undecoded and available values. Sensor attributes retain the raw value, source, observation time and unresolved reason.",
        "",
        "Indexed replies use exact target/index echoes and separate element entities. A generic element index is never labelled M1/M2 or converted to a combined gate percentage. Indexed writes stay blocked until the identity and write layout are verified. Arrays larger than the bounded element limit are not scanned.",
        "",
        f"{len(ADDITIONAL_SETTINGS)} additional scalar/enum SET codecs are prepared behind mandatory session-scoped menu permissions, complete INFO and existing movement/calibration guards. The native menu wire decoder and role mapping are missing, so these additional writes remain read-only in shipped installations. They are not counted as writable app parity and no unavailable placeholder controls are added for them.",
        "",
        "## Completing the missing permissions",
        "",
        "`MenuEntry.from_decoded_fields` implements the recovered Java constructor's permission fields. It consumes already-decoded fields, not binary DMP replies. `MenuWireDecoder.decode` fails before dispatch. A future adapter must recover STD_MENU framing/continuation and binary decoding, validate the current role and emit scoped `MenuPermission` evidence. The parameter engine checks command identity, device, target and session generation, and revokes grants on reconnect. Ranges and a writable DoorAction are never treated as installer permission.",
        "",
        "Unknown wire formats, units, per-motor layouts, additional Pro actions and unverified bindings remain listed in the gap report. New clues should fill a decoder, binding, profile or index identity under these contracts, without replacing the HA adapters.",
        "",
        "## Upgrade and testing",
        "",
        "Install the beta and restart HA. Existing identities, saved calibration and learned speed bands remain intact. Optional entities are under the device's disabled entities. Start with read-only comparisons against the apps; changing force, safety settings or controller relearning is not required.",
        "",
        "Also verify a first load and a reload. Startup now loads core state before optional diagnostics. Failed/cancelled setup fences and closes its owned session; diagnostics work before setup completes. An absent module name produces an unknown text value instead of a validation error.",
        "",
        "## Complete definition ledger",
        "",
        "Bindings below are cross-checked evidence, not universal device support or write authorization. Read availability still depends on actual INFO/value replies. App IDs are included only in the source data; dispatch uses reviewed bindings.",
        "",
        "| Symbol | DMP binding | Read path | Write path / gap |",
        "| --- | --- | --- | --- |",
    ]
    for definition in PARAMETERS:
        binding = (
            "/".join(f"{value:02X}" for value in definition.binding)
            if definition.binding
            else "unresolved"
        )
        read = definition.existing_read or (
            "selective INFO/GET"
            if definition.safe_read
            else "existing action"
            if definition.reviewed_action
            else "blocked"
        )
        write = (
            "existing t4." + definition.reviewed_action
            if definition.reviewed_action
            else "existing scalar setter"
            if definition.setting and not definition.setting.requires_menu_permission
            else "controller.menu_wire"
            if definition.safe_read
            else definition.gap
        )
        configuration.append(
            f"| `{definition.symbol}` | `{binding}` | {read} | {write} |"
        )
    configuration.append("")
    return {
        "docs/app_parity.md": "\n".join(lines) + "\n",
        "docs/protocol_gaps.md": "\n".join(gaps),
        "docs/controller_configuration.md": "\n".join(configuration),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in documents().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Outdated generated documentation: {name}")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
